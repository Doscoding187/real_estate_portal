/**
 * Builds the homepage category card images.
 *
 *   pnpm images:categories
 *
 * Reads every original in client/image-originals/categories, writes
 * client/public/images/categories/{name}-{w}.webp (card ratio, attention crop,
 * quality 72, metadata stripped) and client/src/lib/categoryImages.generated.ts
 * (the widths that exist, read by the card component). Idempotent: outputs are
 * rewritten from the originals and stale files for a name are removed.
 */
import { mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { heightForWidth, selectWidths } from './categoryImageWidths.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const sourceDir = path.join(root, 'client', 'image-originals', 'categories');
const outDir = path.join(root, 'client', 'public', 'images', 'categories');
const manifestPath = path.join(root, 'client', 'src', 'lib', 'categoryImages.generated.ts');
const QUALITY = 72;
/** Attention cropping is the default; these originals need a fixed crop to keep the subject. */
const POSITION_OVERRIDES = { apartments: 'left' };

await mkdir(outDir, { recursive: true });
const originals = (await readdir(sourceDir))
  .filter(file => /\.(jpe?g|png)$/i.test(file))
  .sort();

const rows = [];
const manifest = {};

for (const file of originals) {
  const name = path.basename(file, path.extname(file));
  const input = path.join(sourceDir, file);
  const meta = await sharp(input).metadata();
  const { widths, skipped } = selectWidths(meta.width, meta.height);

  for (const stale of await readdir(outDir)) {
    if (stale.startsWith(`${name}-`) && stale.endsWith('.webp')) {
      await rm(path.join(outDir, stale));
    }
  }

  for (const width of widths) {
    const height = heightForWidth(width);
    const target = path.join(outDir, `${name}-${width}.webp`);
    await sharp(input)
      .resize(width, height, { fit: 'cover', position: POSITION_OVERRIDES[name] ?? sharp.strategy.attention })
      .webp({ quality: QUALITY })
      .toFile(target);
    const { size } = await stat(target);
    rows.push({ file: `${name}-${width}.webp`, size: `${width}x${height}`, bytes: size });
  }
  if (skipped.length) {
    console.log(
      `${name}: original ${meta.width}x${meta.height}; skipped widths ${skipped.join(', ')} (larger than the card-ratio crop)`,
    );
  }
  const largest = Math.max(...widths);
  manifest[name] = { widths, width: largest, height: heightForWidth(largest) };
}

console.table(rows);

const body = Object.entries(manifest)
  .map(
    ([name, value]) =>
      `  '${name}': { widths: [${value.widths.join(', ')}], width: ${value.width}, height: ${value.height} },`,
  )
  .join('\n');
await writeFile(
  manifestPath,
  `// Generated by scripts/images/build-category-images.mjs. Do not edit by hand.\n` +
    `export const CATEGORY_IMAGES: Record<string, { widths: number[]; width: number; height: number }> = {\n${body}\n};\n`,
);
console.log(`wrote ${path.relative(root, manifestPath)}`);
