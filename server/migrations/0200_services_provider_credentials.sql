CREATE TABLE `service_provider_credentials` (
  `id` int AUTO_INCREMENT NOT NULL,
  `provider_id` int NOT NULL,
  `credential_type` varchar(80) NOT NULL,
  `title` varchar(180) NOT NULL,
  `issuing_body` varchar(180) NULL,
  `reference` varchar(120) NULL,
  `private_storage_key` varchar(500) NOT NULL,
  `original_file_name` varchar(255) NOT NULL,
  `mime_type` varchar(80) NOT NULL,
  `byte_size` int NOT NULL,
  `status` enum('pending','verified','rejected') NOT NULL DEFAULT 'pending',
  `submitted_by_user_id` int NOT NULL,
  `reviewed_by_user_id` int NULL,
  `review_note` varchar(1000) NULL,
  `reviewed_at` timestamp NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `service_provider_credentials_id` PRIMARY KEY(`id`),
  CONSTRAINT `ux_service_provider_credentials_storage_key` UNIQUE(`private_storage_key`),
  INDEX `idx_service_provider_credentials_provider_status` (`provider_id`,`status`),
  CONSTRAINT `svc_credentials_provider_fk` FOREIGN KEY (`provider_id`) REFERENCES `partners`(`id`) ON DELETE cascade ON UPDATE no action,
  CONSTRAINT `svc_credentials_submitter_fk` FOREIGN KEY (`submitted_by_user_id`) REFERENCES `users`(`id`) ON DELETE restrict ON UPDATE no action,
  CONSTRAINT `svc_credentials_reviewer_fk` FOREIGN KEY (`reviewed_by_user_id`) REFERENCES `users`(`id`) ON DELETE set null ON UPDATE no action
);
