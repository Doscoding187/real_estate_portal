CREATE TABLE `development_place_assignments` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `development_id` INT NOT NULL,
  `phase_id` INT NULL,
  `place_id` VARCHAR(40) NOT NULL,
  `assignment_kind` ENUM('site', 'presentation', 'estate') NOT NULL DEFAULT 'site',
  `review_state` ENUM('pending_review', 'accepted', 'rejected', 'withdrawn') NOT NULL DEFAULT 'pending_review',
  `evidence_reference` VARCHAR(1000) NOT NULL,
  `created_by_user_id` INT NULL,
  `reviewed_by_user_id` INT NULL,
  `reviewed_at` TIMESTAMP NULL,
  `review_note` TEXT NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_development_place_assignments_development_state_kind` (`development_id`, `review_state`, `assignment_kind`),
  KEY `idx_development_place_assignments_place_state_kind` (`place_id`, `review_state`, `assignment_kind`),
  KEY `idx_development_place_assignments_phase_id` (`phase_id`),
  CONSTRAINT `fk_development_place_assignments_development` FOREIGN KEY (`development_id`) REFERENCES `developments` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_development_place_assignments_phase_owner` FOREIGN KEY (`development_id`, `phase_id`) REFERENCES `development_phases` (`development_id`, `id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_development_place_assignments_place` FOREIGN KEY (`place_id`) REFERENCES `place` (`place_id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT `fk_development_place_assignments_created_by_user` FOREIGN KEY (`created_by_user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_development_place_assignments_reviewed_by_user` FOREIGN KEY (`reviewed_by_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `chk_development_place_assignment_review_metadata` CHECK ((`review_state` = 'pending_review' AND `reviewed_by_user_id` IS NULL AND `reviewed_at` IS NULL) OR (`review_state` IN ('accepted', 'rejected', 'withdrawn') AND `reviewed_by_user_id` IS NOT NULL AND `reviewed_at` IS NOT NULL)),
  CONSTRAINT `chk_development_place_assignment_evidence_reference` CHECK (CHAR_LENGTH(TRIM(`evidence_reference`)) > 0)
);
