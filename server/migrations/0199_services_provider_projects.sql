CREATE TABLE `service_provider_projects` (
  `id` int AUTO_INCREMENT NOT NULL,
  `provider_id` int NOT NULL,
  `title` varchar(180) NOT NULL,
  `description` text NULL,
  `service_category` enum('home_improvement','finance_legal','moving','inspection_compliance','insurance','media_marketing') NOT NULL,
  `canonical_place_id` varchar(40) NULL,
  `cover_image_url` varchar(500) NULL,
  `gallery` json NULL,
  `moderation_status` enum('draft','pending','published','rejected') NOT NULL DEFAULT 'draft',
  `reviewed_by_user_id` int NULL,
  `moderation_note` varchar(1000) NULL,
  `reviewed_at` timestamp NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `service_provider_projects_id` PRIMARY KEY(`id`),
  INDEX `idx_service_provider_projects_provider_status` (`provider_id`,`moderation_status`),
  INDEX `idx_service_provider_projects_place` (`canonical_place_id`),
  CONSTRAINT `svc_projects_provider_fk` FOREIGN KEY (`provider_id`) REFERENCES `partners`(`id`) ON DELETE cascade ON UPDATE no action,
  CONSTRAINT `svc_projects_place_fk` FOREIGN KEY (`canonical_place_id`) REFERENCES `place`(`place_id`) ON DELETE restrict ON UPDATE restrict,
  CONSTRAINT `svc_projects_reviewer_fk` FOREIGN KEY (`reviewed_by_user_id`) REFERENCES `users`(`id`) ON DELETE set null ON UPDATE no action
);
