CREATE TABLE `development_inventory_items` (
  `id` int NOT NULL AUTO_INCREMENT,
  `development_id` int NOT NULL,
  `phase_id` int NOT NULL,
  `unit_type_id` varchar(36) NOT NULL,
  `internal_identifier` varchar(100) NOT NULL,
  `public_identifier` varchar(100),
  `transaction_type` enum('for_sale','for_rent') NOT NULL,
  `status` enum('planned','available','reserved','under_offer','under_contract','sold','leased','withdrawn','legal_hold','reconciliation_required') NOT NULL DEFAULT 'planned',
  `sale_price` decimal(15,2),
  `rent_price` decimal(15,2),
  `version_id` int NOT NULL DEFAULT 1,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_development_inventory_internal_identifier` (`development_id`,`internal_identifier`),
  UNIQUE KEY `uq_development_inventory_public_identifier` (`development_id`,`public_identifier`),
  KEY `idx_development_inventory_development_phase_status` (`development_id`,`phase_id`,`status`),
  KEY `idx_development_inventory_phase_status_mode` (`phase_id`,`status`,`transaction_type`),
  KEY `idx_development_inventory_type_status` (`unit_type_id`,`status`),
  CONSTRAINT `development_inventory_items_development_id_developments_id_fk` FOREIGN KEY (`development_id`) REFERENCES `developments` (`id`) ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT `development_inventory_items_phase_id_development_phases_id_fk` FOREIGN KEY (`phase_id`) REFERENCES `development_phases` (`id`) ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT `development_inventory_items_unit_type_id_unit_types_id_fk` FOREIGN KEY (`unit_type_id`) REFERENCES `unit_types` (`id`) ON DELETE RESTRICT ON UPDATE NO ACTION
);
