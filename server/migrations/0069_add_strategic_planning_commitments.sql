CREATE TABLE `strategic_planning_commitments` (
  `id` int NOT NULL AUTO_INCREMENT,
  `objective_id` int NOT NULL,
  `title` varchar(200) NOT NULL,
  `description` text,
  `owner_user_id` int NOT NULL,
  `status` enum('open','in_progress','completed','dropped') NOT NULL DEFAULT 'open',
  `due_date` date,
  `drop_reason` text,
  `completed_at` timestamp NULL,
  `dropped_at` timestamp NULL,
  `created_by_user_id` int NOT NULL,
  `updated_by_user_id` int NOT NULL,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_spc_objective_status` (`objective_id`,`status`),
  KEY `idx_spc_objective_due_date` (`objective_id`,`due_date`),
  KEY `idx_spc_owner_status` (`owner_user_id`,`status`),
  KEY `idx_spc_status_due_date` (`status`,`due_date`),
  CONSTRAINT `fk_spc_objective` FOREIGN KEY (`objective_id`) REFERENCES `strategic_planning_objectives` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_spc_owner` FOREIGN KEY (`owner_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_spc_created_by` FOREIGN KEY (`created_by_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_spc_updated_by` FOREIGN KEY (`updated_by_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT
);
