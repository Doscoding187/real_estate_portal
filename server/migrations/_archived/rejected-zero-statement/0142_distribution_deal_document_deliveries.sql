  CONSTRAINT `distribution_deal_document_deliveries_deal_document_id_fk` FOREIGN KEY (`deal_document_id`) REFERENCES `distribution_deal_documents` (`id`) ON DELETE CASCADE,
  CONSTRAINT `distribution_deal_document_deliveries_deal_id_fk` FOREIGN KEY (`deal_id`) REFERENCES `distribution_deals` (`id`) ON DELETE CASCADE,
  CONSTRAINT `distribution_deal_document_deliveries_developer_organisation_id_fk` FOREIGN KEY (`developer_organisation_id`) REFERENCES `developer_organisations` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `distribution_deal_document_deliveries_delivered_by_fk` FOREIGN KEY (`delivered_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `distribution_deal_document_deliveries_acknowledged_by_fk` FOREIGN KEY (`acknowledged_by`) REFERENCES `users` (`id`) ON DELETE RESTRICT
);
