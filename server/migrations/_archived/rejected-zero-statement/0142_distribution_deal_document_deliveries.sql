  CONSTRAINT `ux_distribution_deal_document_delivery_version` UNIQUE (`deal_document_id`,`delivery_version`),
  KEY `idx_distribution_deal_document_deliveries_organisation` (`developer_organisation_id`,`delivered_at`),
  KEY `idx_distribution_deal_document_deliveries_deal` (`deal_id`),
