CREATE TABLE `distribution_deal_document_deliveries` (
  `id` int AUTO_INCREMENT NOT NULL,
  `deal_document_id` int NOT NULL,
  `deal_id` int NOT NULL,
  `delivery_version` int NOT NULL DEFAULT 1,
  `developer_organisation_id` int NOT NULL,
  `document_code` varchar(80) NOT NULL,
  `document_label` varchar(160) NOT NULL,
  `document_file_name` varchar(255) NOT NULL,
  `document_submitted_at` timestamp,
  `delivered_by` int NOT NULL,
  `delivered_at` timestamp NOT NULL DEFAULT (now()),
  `acknowledged_by` int,
  `acknowledged_at` timestamp,
  `acknowledgement_note` text,
