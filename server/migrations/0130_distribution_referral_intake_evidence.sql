-- Store only private evidence metadata and retention work state; never place prospect contact details in an intake draft.
CREATE TABLE `distribution_referral_intake_evidence` (
  `id` int AUTO_INCREMENT NOT NULL,
  `evidence_uuid` varchar(36) NOT NULL,
  `session_id` int NOT NULL,
  `evidence_type` enum('sharing_permission','privacy_notice','identity_document','credit_authorization') NOT NULL,
  `storage_adapter` enum('local','s3'),
  `storage_key` varchar(255),
  `mime_type` varchar(120),
  `byte_size` int,
  `sha256` varchar(64),
  `uploaded_by_user_id` int,
  `review_status` enum('pending','verified','rejected','not_required') NOT NULL DEFAULT 'pending',
  `storage_status` enum('stored','deleting','deletion_failed','deleted') NOT NULL DEFAULT 'stored',
  `retention_due_at` timestamp NOT NULL,
  `deletion_attempt_count` int NOT NULL DEFAULT 0,
  `deletion_claimed_at` timestamp,
  `deletion_lease_token` varchar(36),
  `deletion_next_attempt_at` timestamp,
  `deletion_last_error_code` varchar(120),
  `deleted_at` timestamp,
  `created_at` timestamp NOT NULL DEFAULT (now()),
  `updated_at` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `distribution_referral_intake_evidence_id` PRIMARY KEY (`id`),
  CONSTRAINT `ux_distribution_referral_intake_evidence_uuid` UNIQUE (`evidence_uuid`),
  CONSTRAINT `ux_distribution_referral_intake_evidence_storage_key` UNIQUE (`storage_key`),
  KEY `idx_distribution_referral_intake_evidence_session_type` (`session_id`,`evidence_type`),
  KEY `idx_distribution_referral_intake_evidence_retention` (`storage_status`,`retention_due_at`,`deletion_next_attempt_at`),
  KEY `idx_distribution_referral_intake_evidence_deletion_lease` (`storage_status`,`deletion_claimed_at`),
  CONSTRAINT `distribution_referral_intake_evidence_session_id_fk` FOREIGN KEY (`session_id`) REFERENCES `distribution_referral_intake_sessions` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `distribution_referral_intake_evidence_uploaded_by_user_id_fk` FOREIGN KEY (`uploaded_by_user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL
);
