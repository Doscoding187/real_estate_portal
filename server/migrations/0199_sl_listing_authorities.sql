CREATE TABLE `sl_listing_authorities` (
  `id` INT NOT NULL AUTO_INCREMENT,
  `place_id` INT NOT NULL,
  `agent_user_id` INT NOT NULL,
  `responsible_party_id` INT NOT NULL,
  `status` ENUM('draft','pending_review','approved','rejected','revoked','expired','superseded') NOT NULL DEFAULT 'draft',
  `effective_at` DATETIME NOT NULL,
  `expires_at` DATETIME NOT NULL,
  `reviewed_by_user_id` INT NULL,
  `reviewed_at` DATETIME NULL,
  `review_reason` VARCHAR(500) NULL,
  `revoked_by_user_id` INT NULL,
  `revoked_at` DATETIME NULL,
  `revocation_reason` VARCHAR(500) NULL,
  `created_by_user_id` INT NOT NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_sl_listing_authorities_place_status` (`place_id`,`status`,`effective_at`,`expires_at`),
  KEY `idx_sl_listing_authorities_agent_status` (`agent_user_id`,`status`),
  CONSTRAINT `fk_sl_listing_authorities_place` FOREIGN KEY (`place_id`) REFERENCES `sl_places` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_sl_listing_authorities_agent` FOREIGN KEY (`agent_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_sl_listing_authorities_party` FOREIGN KEY (`responsible_party_id`) REFERENCES `sl_responsible_parties` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_sl_listing_authorities_reviewer` FOREIGN KEY (`reviewed_by_user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_sl_listing_authorities_revoker` FOREIGN KEY (`revoked_by_user_id`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_sl_listing_authorities_creator` FOREIGN KEY (`created_by_user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `chk_sl_listing_authorities_dates` CHECK (`expires_at` > `effective_at`)
);
